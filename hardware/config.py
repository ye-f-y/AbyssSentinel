PUBLISH_INTERVAL = 5  # need.md 要求每5秒

# ============================================================
# RS485 / Modbus 引脚配置 (ESP32-S3 行空板K10)
# ============================================================
# 接线（need.md §3.3-3.4）：
#   TTL模块 TXD → ESP32 IO16 (RX)
#   TTL模块 RXD → ESP32 IO17 (TX)
#   模块为自动方向切换，无需 DE/RE 控制引脚
RS485_TX_PIN = 16
RS485_RX_PIN = 17
RS485_UART_ID = 1       # UART1（诊断确认）
RS485_BAUDRATE = 9600   # 两个传感器都是 9600

# ============================================================
# 继电器引脚
# ============================================================
# 接线（need.md §3.3）：继电器 IN → ESP32 IO15
RELAY_PIN = 15

# ============================================================
# 传感器 Modbus 地址（need.md §3.2）
# ============================================================
# 气象传感器 RS-FSXCS-N01-3：地址已从出厂默认0x02改为0x03
# 土壤传感器 SN-3001-TR-ECTHPH-N01：地址保持出厂默认0x02
WEATHER_ADDR = 0x03
SOIL_ADDR = 0x02

# ============================================================
# 气象站寄存器映射（need.md §3.2）
# 起始地址 0x01F8，8个连续寄存器
# ============================================================
WEATHER_REGISTERS = {
    # 名称:         (寄存器地址, 缩放倍数, 单位)
    "air_humidity":  (0x01F8, 0.1,  "%RH"),    # 空气湿度 ÷10
    "air_temp":      (0x01F9, 0.1,  "℃"),      # 气温 ÷10
    "noise":         (0x01FA, 0.1,  "dB"),      # 噪音分贝 ÷10
    "wind_speed":    (0x01FB, 0.1,  "m/s"),     # 风速 ÷10
    "wind_dir":      (0x01FC, 1.0,  "°"),       # 风向角度 直接读
    "pressure":      (0x01FD, 0.1,  "kPa"),     # 大气压强 ÷10
    "wind_power":    (0x01FE, 1.0,  "级"),      # 风力等级 直接读(0-17)
    "light":         (0x01FF, 1.0,  "Lux"),     # 光照强度 直接读
}

# ============================================================
# 土壤传感器寄存器映射（need.md §3.2）
# 起始地址 0x0000，4个连续寄存器
# ============================================================
SOIL_REGISTERS = {
    # 名称:            (寄存器地址, 缩放倍数, 单位)
    "soil_moisture":    (0x0000, 0.1,  "%RH"),   # 土壤湿度 ÷10
    "soil_temp":        (0x0001, 0.1,  "℃"),     # 土壤温度 ÷10
    "soil_ec":          (0x0002, 1.0,  "μS/cm"), # 电导率 直接读
    "soil_ph":          (0x0003, 0.1,  "pH"),    # 酸碱度 ÷10
}

# 一次读取连续寄存器的最大数量
MODBUS_MAX_READ = 10
